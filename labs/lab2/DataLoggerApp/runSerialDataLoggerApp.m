%   Either run serialDataLoggerApp() and configure the parameters from GUI,
%   or pass the desired settings from command line as specified below.

%   select serial port 
%   Note: use serialportlist() to check for available serial ports
serialPortName = "/dev/tty.usbmodem103"; 

%   define packet specifier
packetSpec = {'3*single', 'uint16', '2*int32'};

%   select baud rate
baudRate = 115200;

%   configure scopes
plotsGridSize = [3, 1];
plotsContentList = [ ...
    1, 1, 1; ...    %   format: scope id, signal id, component id
    1, 1, 2; ...    %
    1, 1, 3; ...    %
    2, 2, 1; ...    %
    3, 3, 1; ...    %
    3, 3, 2];       %

%   start serialDataLoggerApp with specified input arguments

%{
    serialDataLoggerApp( ... 
        "SerialPortName", serialPortName, ...
        "PacketSpec", packetSpec, ...
        "baudRate", baudRate, ...
        "assertDTR", true, ...
        "enableCOBS", true, ...
        "enableNullTerminator", true, ...
        "bufferSize", 2000, ...
        "txSampleTime", 0.01, ...
        "enableLogToWorkspace", true, ...
        "enableSaveOnExit", true, ...
        "varName", "data", ...
        "plotsGridSize", plotsGridSize, ...
        "plotsContentList", plotsContentList, ...
        "plotsDuration", 10, ...
        "plotsRefreshRatio", 8);
%}

app = serialDataLoggerApp( ...
    serialPortName=serialPortName, baudRate=115200, ...
    enableStartStopCmds=true, ...
    packetSpec={'2*single','2*single'}, ...
    enableCOBS=true, enableNullTerminator=true, ...
    txSampleTime=0.01, bufferSize=100000, ...
    enableLogToWorkspace=true, enableSaveOnExit=true, ...
    varName="data", ...
    plotsGridSize=[2 1], ...
    plotsContentList=[1 1 1; 1 1 2; 2 2 1; 2 2 2], ...
    plotsDuration=5, plotsRefreshRatio=10);

% retrieve and save the motor measurements with:
%{
    % After clicking Save to workspace:
    assert(data.size > 0, 'No samples acquired');
    t = data.time - data.time(1);
    w1 = data.signals{1}(1,:);
    w2 = data.signals{1}(2,:);
    u1 = data.signals{2}(1,:);
    u2 = data.signals{2}(2,:);
    save('motor_trial01.mat', 'data');
%}